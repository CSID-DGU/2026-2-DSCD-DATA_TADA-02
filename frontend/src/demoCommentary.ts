export function compareCommentary(section: Section, floor: string) {
  if (section === 'location') return null;
  const copy = section === 'rent' ? rentCopy[floor] : compareCopy[section];
  return copy ? commentary(compareQuestions[section], copy, section) : null;
}

export function detailCommentary(code: string, section: Section) {
  if (section === 'rent') return null;
  const copy = detailCopy[code]?.[section];
  return copy ? commentary(detailQuestions[section], copy, section) : null;
}
